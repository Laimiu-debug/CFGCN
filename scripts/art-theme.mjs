// Pure projection: CSS is the canonical palette, including the engine colors.
export function rustPalette(css) {
  const colors = [...css.matchAll(/--([\w-]+):\s*#([\da-f]{6}|[\da-f]{8})\s*;/gi)];
  const rows = colors.map(([, name, hex]) => {
    const channels = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16));
    channels.push(hex.length === 8 ? parseInt(hex.slice(6), 16) : 255);
    return `    ("${name}", [${channels.join(', ')}]),`;
  });
  return `// Generated by npm run sync:art from packages/ui/src/tokens.css.\n// Edit the canonical tokens and the art standard together.\npub const COLORS: &[(&str, [u8; 4])] = &[\n${rows.join('\n')}\n];\n`;
}

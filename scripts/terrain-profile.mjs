// A single expression source generates CPU simulation, Blender and GPU terrain.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(
  fs.readFileSync(path.join(root, 'packages/game-core/data/xiyou-terrain.json'), 'utf8'),
);
const banner = 'Generated by scripts/terrain-profile.mjs from xiyou-terrain.json. Do not edit.';
let py = `# ${banner}\nfrom math import sin, cos\ndef mix(a,b,t): return a+(b-a)*t\ndef t_smooth(a,b,x):\n    t=max(0.,min(1.,(x-a)/(b-a)))\n    return t*t*(3.-2.*t)\n`;
let rs = `//! ${banner}\nfn sin(x:f32)->f32{x.sin()}\nfn cos(x:f32)->f32{x.cos()}\nfn abs(x:f32)->f32{x.abs()}\nfn mix(a:f32,b:f32,t:f32)->f32{a+(b-a)*t}\nfn t_smooth(a:f32,b:f32,x:f32)->f32{let t=((x-a)/(b-a)).clamp(0.,1.);t*t*(3.-2.*t)}\n`;
let wg = `// ${banner}\nfn t_smooth(a:f32,b:f32,x:f32)->f32 { let t=clamp((x-a)/(b-a),0.0,1.0);return t*t*(3.0-2.0*t); }\n`;
const props = JSON.parse(
  fs.readFileSync(path.join(root, 'apps/xiyou/art/world-props.json'), 'utf8'),
);
const n = (v) => (Number.isInteger(v) ? v.toFixed(1) : String(v));
const propRs = `//! ${banner}\nuse crate::Point;\npub fn world_props(region:u8)->Vec<(Point,f32)>{\nlet entries:&[(f32,f32,f32)]=match region {\n${props.map((group, i) => `${i}=>&[${group.map((p) => '(' + p.map(n).join(',') + ')').join(',')}],`).join('\n')}\n_=>&[],\n};\nentries.iter().map(|&(x,z,s)|(Point::new(x,z),s)).collect()\n}\n`;
const layout = JSON.parse(
  fs.readFileSync(path.join(root, 'apps/xiyou/art/world-layout.json'), 'utf8'),
);
const layoutRs = `//! ${banner}\nuse crate::Point;\n#[derive(Clone, Copy)]\npub struct WorldStone{pub pos:Point,pub scale:[f32;3],pub angle:f32,pub event:u8}\npub const STONE_FOOTPRINT:[f32;2]=[${layout.stone_footprint.map(n)}];\npub const TREE_FOOTPRINT:[f32;2]=[${layout.tree_footprint.map(n)}];\npub const WORLD_STONES:&[WorldStone]=&[\n${layout.stones.map((s) => `WorldStone{pos:Point{x:${n(s.x)},z:${n(s.z)}},scale:[${s.scale.map(n)}],angle:${n(s.angle)},event:${s.event}},`).join('\n')}\n];\n`;
for (const fn of spec.functions) {
  py += `def ${fn.name}(${fn.args.join(',')}):\n`;
  rs += `pub fn ${fn.name}(${fn.args.map((a) => a + ':f32').join(',')})->f32{\n`;
  wg += `fn ${fn.name}(${fn.args.map((a) => a + ':f32').join(',')})->f32{\n`;
  for (const [name, expression] of fn.steps) {
    py += `    ${name}=${expression}\n`;
    rs += name === 'result' ? `${expression}\n` : `let ${name}=${expression};\n`;
    wg += `let ${name}=${expression};\n`;
  }
  py += '    return result\n';
  rs += '}\n';
  wg += 'return result;\n}\n';
}
for (const [file, body] of Object.entries({
  'apps/xiyou/art/terrain_profile.py': py,
  'packages/game-core/src/terrain_profile.rs': rs,
  'packages/game-core/src/world_props_profile.rs': propRs,
  'packages/game-core/src/world_layout_profile.rs': layoutRs,
  'apps/website/public/games/xiyou/assets/terrain_profile.wesl': wg,
})) {
  const dest = path.join(root, file);
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(dest, 'utf8').replace(/\s/g, '') !== body.replace(/\s/g, ''))
      throw Error('stale terrain ' + file);
  } else if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== body) {
    fs.writeFileSync(dest, body);
  }
}
for (const file of ['series_mesh.wesl', 'series_paint.wesl']) {
  const dest = path.join(root, 'apps/website/public/games/xiyou/assets', file);
  if (!fs.existsSync(dest)) continue;
  const body = fs.readFileSync(dest, 'utf8').replaceAll('\r\n', '\n');
  if (!body.includes('// TERRAIN_PROFILE_START')) continue;
  const updated = body.replace(
    /\/\/ TERRAIN_PROFILE_START[\s\S]*?\/\/ TERRAIN_PROFILE_END/,
    `// TERRAIN_PROFILE_START\n${wg}// TERRAIN_PROFILE_END`,
  );
  if (process.argv.includes('--check')) {
    if (updated !== body) throw Error('stale shader ' + file);
  } else if (updated !== body) fs.writeFileSync(dest, updated);
}
console.log('Terrain profile ' + (process.argv.includes('--check') ? 'verified' : 'generated'));
